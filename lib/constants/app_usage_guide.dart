/// User-facing guide shared by the software information dialog.
const appUsageGuide = '''待办
新建时可选普通事项、每日打卡或合集。事项可设置标签、截止时间及时间标蓝；圆圈切换完成状态，完成后先播放动画再移出当前列表。
事项合集右侧“部分显示”可选择显示哪些合集，支持全选、全不选；右滑合集可隐藏，数据不会删除。长按合集可改名、一键完成或固定合集。非空合集的事项全部完成后，事项先消失，合集稍后自动移除，已完成事项仍保留；固定合集不会自动移除，取消固定时若仍全部完成则自动移除。空合集保留。
待办不提供左滑删除，也没有一分钟恢复按钮。长按事项可编辑；每日打卡保留原有上下滑动删除。右上角圆圈切换未完成与已完成。

记录
通过标题和标签搜索笔记，使用合集分类。右滑任意笔记进入多选，左滑任意笔记退出多选；可批量移动或删除。普通浏览状态左滑删除笔记，一分钟内可通过恢复入口找回，超过一分钟不再恢复。
点击正文进入编辑，支持三级标题、加粗、斜体、下划线、高亮、引用、列表、分隔线和上下标。三级标题始终加粗；在笔记标题末尾换行，会在正文开头插入空行并移动光标。
支持插入和粘贴 Markdown 表格，最多 12 列。长按单元格可删行、删列或向右增列；表头菜单可复制、删除表格或下移一行，表格下连续两次退格可删除整表。

快捷操作与连携
文本整理包括标点管理、空格管理、清除空行和打乱无序列表。标点管理清理段首异常标点，并补全正文、引用块和列表项末尾句号，包括以引号、括号或书名号结尾的段落；括号或引号内、前方已有句末符号时不补外层句号，并清理多余句号。段首引号未闭合时补齐，行内代码和代码块保持原样。空格管理将中英文之间及运算符号、斜线、反斜线、@ 两侧空格统一为一个。格式调整包括标题升级／降级、取消加粗、首字母大写；取消加粗不改变标题本身的粗体。
空格管理跳过笔记标题及一至三级标题。快捷操作根据当前内容显示；有选框列表时提供“勾选全部”和“清空勾选”。操作后停留在浏览状态，可继续操作或撤回。点击连携旁的铅笔编辑；全部选项始终保留，长按整行拖入已选中区域可加入，拖回未选中区域可移除，在已选中区域拖动排序。保存后点击“连携操作”一次执行全部步骤，可整体撤回。

页面设置与导出
浏览页“页面设置”调整日常笔记样式，并将改动用于长图；长图页“图片设置”只改变导出样式，不影响日常浏览。“开头空两格”仅在图片设置中提供。可调整字号、字间距、行间距、段间距、留白及元信息显示。
导出支持复制 Markdown 和无损 PNG 长图。复制不会自动弹出键盘；长图按设备像素密度生成。保存成功或打开系统分享后记住图片设置并返回浏览页，最终发送由分享应用完成。笔记正文灰白显示，原始彩色格式数据保留；删除操作为红色。

时历
查看事件与周期倒计时；不足 24 小时显示红点，到期删除当前项并按周期推进。时历卡片仅支持左滑删除。

设置与备份
可调整显示顺序、导出备份、从 JSON 文件或粘贴的 JSON 内容导入，读取后弹窗确认；取消不改数据。首次导出授权备份文件夹后，每日自动备份一次完整数据并清理超过 7 天的自动备份；后台时间由 Android 调度，启动、回到前台与跨日使用时补查。数据保存在本机，请定期备份。应用启动恢复上次使用的模块。''';
